"""Step 4 — does adding serve side to the win-prob eval help it predict points?

Run:  python experiments/serve_side/model_eval.py

Wires ``serve_side`` into the score-aware eval the same way ``pressure`` and
``lead`` are (``load_points`` tags each point, ``ScoreAwareModel(components=...)``
folds the tag into the shrinkage backoff), then scores it on held-out points
against the score-blind baseline and against pressure. If side carried its own
predictive signal — beyond the fact that it correlates with the rally states the
eval already sees — a side-aware eval would beat the blind one out of sample.

Prints a table and writes reports/serve_side_model.md.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "score_aware_eval"))
sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))

from compare import eval_model, server_win_by  # noqa: E402
from model import ScoreAwareModel, in_test, load_points  # noqa: E402

from match_charting_project.analysis.coverage import connect  # noqa: E402
from match_charting_project.paths import PROJECT_ROOT  # noqa: E402

SAMPLE = 500_000
TRAIN_EVAL_CAP = 60_000
GLABEL = {"M": "Men", "W": "Women"}


def models_for(train):
    return {
        "score-blind": ScoreAwareModel(use_score=False).fit(train),
        "serve_side-coarse": ScoreAwareModel(score_pos="coarse",
                                             components=("serve_side",)).fit(train),
        "serve_side-fine": ScoreAwareModel(score_pos="fine",
                                           components=("serve_side",)).fit(train),
        "pressure-coarse": ScoreAwareModel(score_pos="coarse",
                                           components=("pressure",)).fit(train),
        "pressure+side": ScoreAwareModel(score_pos="coarse",
                                         components=("pressure", "serve_side")).fit(train),
    }


def main():
    con = connect(read_only=True)
    md = ["# Serve side — does it help the win-prob eval? (Step 4)", ""]
    md.append("*Generated by `experiments/serve_side/model_eval.py`. Each eval predicts "
              "P(server wins) on the same held-out non-terminal positions (match-level "
              "train/test split, no point leakage). Δ vs blind is the percent improvement "
              "in held-out log-loss; positive means the side tag earned its keep.*")
    md.append("")
    best = -1e9
    for g in ("M", "W"):
        pts = load_points(con, g, sample=SAMPLE)
        train = [p for p in pts if not in_test(p.match_id)]
        test = [p for p in pts if in_test(p.match_id)]
        models = models_for(train)
        base = eval_model(models["score-blind"], test)

        md.append(f"## {GLABEL[g]} — {base['n']:,} held-out positions "
                  f"({len(test):,} points)\n")
        md.append("| eval | train LL | test LL | Δ vs blind | Brier |")
        md.append("|---|--:|--:|--:|--:|")
        print(f"\n=== {GLABEL[g]} — {base['n']:,} held-out positions ===")
        print(f"{'eval':<20}{'train LL':>10}{'test LL':>10}{'Δ vs blind':>12}{'Brier':>9}")
        for name, m in models.items():
            tr = eval_model(m, train, cap=TRAIN_EVAL_CAP)["log_loss"]
            te = eval_model(m, test)
            d = 100 * (base["log_loss"] - te["log_loss"]) / base["log_loss"]
            if name != "score-blind":
                best = max(best, d)
            md.append(f"| {name} | {tr:.4f} | {te['log_loss']:.4f} | {d:+.2f}% | "
                      f"{te['brier']:.4f} |")
            print(f"{name:<20}{tr:>10.4f}{te['log_loss']:>10.4f}{d:>+11.2f}%{te['brier']:>9.4f}")

        wp = server_win_by(test, "serve_side")
        md.append("")
        md.append("Marginal server-win% by side: "
                  + " · ".join(f"**{k}** {v[0]:.1%} (n={v[1]:,})"
                               for k, v in sorted(wp.items()) if k in ("deuce", "ad")))
        md.append("")

    con.close()
    verdict = ("helped" if best > 0.1 else
               "did not help — side is already implicit in the rally state the eval sees")
    md.append("## Verdict")
    md.append("")
    md.append(f"Best side-aware change to held-out log-loss: **{best:+.2f}%** — {verdict}.")
    md.append("")
    (PROJECT_ROOT / "reports" / "serve_side_model.md").write_text("\n".join(md) + "\n")
    print(f"\nVERDICT: best side-aware Δ log-loss = {best:+.2f}% -> "
          f"{'helped' if best > 0.1 else 'did NOT help'}")
    print("wrote reports/serve_side_model.md")


if __name__ == "__main__":
    main()
